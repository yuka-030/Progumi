def seed():
    db = SessionLocal()
    try:
        existing = db.query(Term).count()
        if existing > 0:
            print(f"既にデータが存在します（{existing}件）。スキップします。")
            return

        for data in terms_data:
            term = Term(**data)
            db.add(term)
        db.commit()
        print("✅ Seedデータの投入が完了しました！")
    except Exception as e:
        db.rollback()
        print(f"❌ エラーが発生しました: {e}")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
